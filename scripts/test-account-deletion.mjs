import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
const root=process.env.TEST_SITE_ORIGIN||'http://127.0.0.1:8769';
const response=await fetch(root+'/konto-loeschen');
assert.equal(response.status,200);
const html=await response.text();
assert.match(response.headers.get('content-type'),/^text\/html/);
assert.match(response.headers.get('cache-control'),/no-store/);
assert.equal(response.headers.get('referrer-policy'),'no-referrer');
assert.equal(response.headers.get('x-frame-options'),'DENY');
const script=html.match(/<script>([\s\S]*?)<\/script>/)[1];
assert.ok(response.headers.get('content-security-policy').includes("'sha256-"+createHash('sha256').update(script).digest('base64')+"'"));
assert.match(response.headers.get('content-security-policy'),/frame-ancestors 'none'/);
assert.doesNotMatch(script,/localStorage|sessionStorage|console\.|document\.cookie/);
assert.doesNotMatch(html,/<script[^>]+src=/);
assert.match(script,/scope=local/);
assert.match(script,/luvipro_request_account_deletion_v1/);
assert.match(script,/p_confirmation:'KONTO LOESCHEN'/);
assert.match(html,/nicht installieren/);
assert.match(await (await fetch(root+'/')).text(),/href="\/konto-loeschen"/);
for(const path of ['src/components/international/international-home.tsx','src/components/international/european-home.tsx'])assert.match(readFileSync(path,'utf8'),/\/konto-loeschen/);
console.log('PASS: same-site HTTP route, security headers/CSP, no persistence/third-party scripts, caller-only payload, session cleanup, no app installation and discoverable links. No credentials or deletion requests submitted.');
